import { afterEach, describe, expect, it, vi } from 'vitest'
import { createSessionTitleSync, type SessionTitleUpdate } from './session-title-sync.ts'

const snapshot = (current: string) => ({ current, titles: { [current]: current } })
const tick = () => new Promise(resolve => setImmediate(resolve))
afterEach(() => { vi.unstubAllGlobals() })

describe('session title publisher lifetime', () => {
  it('suspends publication after release and resumes with a newer revision', async () => {
    const send = vi.fn(async () => {})
    const sync = createSessionTitleSync(send, { id: 'page', revision: 0 }, () => 10)
    sync.publish(snapshot('a'), true)
    await tick()
    const release = sync.release()!
    expect(release).toMatchObject({ source: 'page', release: true, current: null, titles: {} })
    sync.publish(snapshot('b'), true, true)
    expect(send).toHaveBeenCalledTimes(1)
    sync.resume()
    sync.publish(snapshot('b'), false)
    await tick()
    expect(send).toHaveBeenCalledTimes(2)
    sync.dispose()
  })
  it('resends unchanged titles when a successful poll reports a new host instance', async () => {
    const send = vi.fn(async () => {})
    const sync = createSessionTitleSync(send)
    sync.observeHost('first')
    sync.publish(snapshot('a'), false)
    await tick()
    expect(sync.observeHost('first')).toBe(false)
    sync.publish(snapshot('a'), false)
    expect(send).toHaveBeenCalledTimes(1)
    expect(sync.observeHost('second')).toBe(true)
    sync.publish(snapshot('a'), false)
    await tick()
    expect(send).toHaveBeenCalledTimes(2)
    expect(sync.observeHost(undefined)).toBe(false)
    sync.dispose()
  })
  it('reannounces unchanged titles after a reconnect without a focus event', async () => {
    const send = vi.fn(async () => {})
    const sync = createSessionTitleSync(send)
    sync.publish(snapshot('a'), false)
    await tick()
    sync.reconnect()
    sync.publish(snapshot('a'), false)
    await tick()
    expect(send).toHaveBeenCalledTimes(2)
    sync.dispose()
  })

  it('stops retrying an unsupported route, including pending and forced updates', async () => {
    const send = vi.fn(async (): Promise<void> => { throw Object.assign(new Error('not found'), { status: 404 }) })
    const sync = createSessionTitleSync(send)
    sync.publish(snapshot('a'), false)
    sync.publish(snapshot('b'), false)
    await tick()
    sync.publish(snapshot('c'), true, true)
    await tick()
    expect(send).toHaveBeenCalledTimes(1)
    send.mockImplementation(async () => {})
    sync.reconnect()
    sync.publish(snapshot('c'), false)
    await tick()
    expect(send).toHaveBeenCalledTimes(2)
    sync.dispose()
  })

  it('retries transient errors on the next publication', async () => {
    const send = vi.fn(async () => { throw new Error('offline') })
    const sync = createSessionTitleSync(send)
    sync.publish(snapshot('a'), false)
    await tick()
    sync.publish(snapshot('a'), false)
    await tick()
    expect(send).toHaveBeenCalledTimes(2)
    sync.dispose()
  })

  it('ignores a late old-host 404 after reconnecting', async () => {
    let rejectOld!: (error: unknown) => void
    const send = vi.fn(async (): Promise<void> => {})
    send.mockImplementationOnce(() => new Promise<void>((_, reject) => { rejectOld = reject }))
    const sync = createSessionTitleSync(send)
    sync.publish(snapshot('a'), false)
    sync.reconnect()
    sync.publish(snapshot('a'), false)
    rejectOld({ status: 404 })
    await tick()
    sync.publish(snapshot('b'), false)
    await tick()
    expect(send).toHaveBeenCalledTimes(3)
    sync.dispose()
  })
  it('works on paired HTTP pages where randomUUID is unavailable', () => {
    vi.stubGlobal('crypto', { getRandomValues: (values: Uint32Array) => values.fill(123) })
    expect(() => createSessionTitleSync(async () => {}).dispose()).not.toThrow()
  })
  it('reannounces an unchanged snapshot after a focus change', async () => {
    const send = vi.fn(async (_update: SessionTitleUpdate, _signal: AbortSignal) => {})
    const sync = createSessionTitleSync(send, { id: 'a', revision: 0 }, () => 1)
    sync.publish(snapshot('a'), true)
    await tick()
    sync.publish(snapshot('a'), true, true)
    await tick()
    expect(send).toHaveBeenCalledTimes(2)
    expect(send.mock.calls[1]![0].revision).toBeGreaterThan(send.mock.calls[0]![0].revision)
    sync.dispose()
  })

  it('coalesces pending snapshots and drops them on disposal', async () => {
    const releases: Array<() => void> = []
    const send = vi.fn((_update: SessionTitleUpdate, _signal: AbortSignal) => new Promise<void>(resolve => { releases.push(resolve) }))
    const page = { id: 'page', revision: 0 }
    const old = createSessionTitleSync(send, page, () => 10)
    old.publish(snapshot('a'), true)
    old.publish(snapshot('b'), true)
    old.publish(snapshot('c'), true)
    old.dispose()
    expect(send.mock.calls[0]![1].aborted).toBe(true)
    const replacement = createSessionTitleSync(send, page, () => 10)
    replacement.publish(snapshot('d'), true)
    expect(send.mock.calls[1]![0].revision).toBeGreaterThan(send.mock.calls[0]![0].revision)
    // Resolve the old request separately, even if the transport ignores abort.
    replacement.dispose()
    releases[0]!()
    releases[1]!()
    await tick()
    expect(send).toHaveBeenCalledTimes(2)
  })

  it('sends only the newest pending snapshot after a slow response', async () => {
    const releases: Array<() => void> = []
    const send = vi.fn((_update: SessionTitleUpdate, _signal: AbortSignal) => new Promise<void>(resolve => { releases.push(resolve) }))
    const sync = createSessionTitleSync(send, { id: 'a', revision: 0 }, () => 1)
    sync.publish(snapshot('a'), true)
    sync.publish(snapshot('b'), true)
    sync.publish(snapshot('c'), true)
    releases[0]!()
    await tick()
    expect(send).toHaveBeenCalledTimes(2)
    expect(send.mock.calls[1]![0].current).toBe('c')
    sync.dispose()
    releases[1]!()
    await tick()
  })

  it('preserves an unsent focus event through a minimized update and a UI reload', async () => {
    const releases: Array<() => void> = []
    const send = vi.fn((_update: SessionTitleUpdate, _signal: AbortSignal) => new Promise<void>(resolve => { releases.push(resolve) }))
    const page = { id: 'a', revision: 0 }
    let time = 10
    const sync = createSessionTitleSync(send, page, () => time++)
    sync.publish(snapshot('initial'), false)
    sync.publish(snapshot('focused'), true, true)
    sync.publish(snapshot('minimized'), false)
    releases[0]!()
    await tick()
    expect(send.mock.calls[1]![0]).toMatchObject({ current: 'minimized', focusedAt: 11, revision: 12 })
    sync.dispose()
    const replacement = createSessionTitleSync(send, page, () => time++)
    replacement.publish(snapshot('replacement'), false)
    expect(send.mock.calls[2]![0]).toMatchObject({ focusedAt: 11, revision: 13 })
    replacement.dispose()
    releases[1]!()
    releases[2]!()
    await tick()
  })
})
